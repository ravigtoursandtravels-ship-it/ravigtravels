document.addEventListener("DOMContentLoaded", () => {
  const tabs = document.getElementById("packageTabsRow");
  const side = document.getElementById("destinationSidebar");
  const heading = document.getElementById("packageHeading");
  const sub = document.getElementById("packageSubheading");
  const routeLine = document.getElementById("routeLine");
  const tbody = document.getElementById("tariffBody");
  const itinerary = document.getElementById("itineraryBody");
  const hotelSwitch = document.getElementById("hotelSwitch");
  const hotelFields = document.getElementById("hotelFields");
  const activeAnchor = document.querySelector("[data-active-package-anchor]");
  const tourSection = document.getElementById("tourPackagesSection");

  if (!tabs || !side || !tbody || !itinerary) return;

  let days = 1;
  let routeKey = "";
  let withHotel = false;

  const rates = {
    "2star": { double: 3000, triple: 4000 },
    "3star": { double: 4000, triple: 5500 }
  };

  const dayText = d => d === 1 ? "One Day" : `${d} Days / ${d - 1} Nights`;
  const packageTabId = d => d === 1 ? "tour-package-1-day" : `tour-package-${d}-days`;
  const slug = value => String(value).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
  const roomCount = () => Math.max(1, Math.min(20, Number.parseInt(document.getElementById("rooms").value || "1", 10)));

  function routeEntries(day = days) {
    return Object.entries(packagesByDays[String(day)] || {});
  }

  function getPackage() {
    return packagesByDays[String(days)]?.[routeKey] || null;
  }

  function setHash(id, replace = false) {
    if (!id) return;
    const url = `${location.pathname}${location.search}#${id}`;
    if (replace) history.replaceState(null, "", url);
    else history.pushState(null, "", url);
  }

  function renderTabs() {
    tabs.innerHTML = Object.keys(packagesByDays).map(day => {
      const d = Number(day);
      const label = d === 1 ? "One Day" : `${d} Days`;
      const note = d === 1 ? "Quick package" : `${d - 1} night${d > 2 ? "s" : ""}`;
      return `<button type="button" id="${packageTabId(d)}" class="package-tab ${d === days ? "active" : ""}" data-days="${d}" aria-pressed="${d === days}">${label}<small>${note}</small></button>`;
    }).join("");

    tabs.querySelectorAll(".package-tab").forEach(button => {
      button.addEventListener("click", () => {
        days = Number(button.dataset.days);
        routeKey = "";
        renderAll();
        setHash(getPackage()?.id, true);
      });
    });
  }

  function cleanRouteLabel(route) {
    return route.replace(/\s*[–-]\s*\d+\s*km$/i, "").replace(/^Coimbatore\s*→\s*/i, "");
  }

  function renderSide() {
    const entries = routeEntries();
    if (!routeKey || !packagesByDays[String(days)]?.[routeKey]) routeKey = entries[0]?.[0] || "";

    side.innerHTML = `<div class="destination-list">${entries.map(([route, pkg]) => `
      <button type="button" id="destination-${pkg.id}" class="destination-btn ${route === routeKey ? "active" : ""}" data-route="${route}" data-destination-id="${pkg.id}">
        <span>${cleanRouteLabel(route)}</span>
        <small><i class="fa-solid fa-chevron-right"></i></small>
      </button>`).join("")}</div>`;

    side.querySelectorAll(".destination-btn").forEach(button => {
      button.addEventListener("click", () => {
        routeKey = button.dataset.route;
        renderSide();
        renderPackage();
        setHash(button.dataset.destinationId);
        if (window.innerWidth < 992) document.getElementById("tariffSection")?.scrollIntoView({ behavior: "smooth", block: "start" });
      });
    });
  }

  function hotelExtra(pkg) {
    if (!withHotel || !pkg?.nights) return 0;
    const type = document.getElementById("hotelType").value;
    const occupancy = document.getElementById("occupancy").value;
    return rates[type][occupancy] * roomCount() * pkg.nights;
  }

  function vehicleDisplay(vehicle) {
    const map = {
      "Sedan (4+1)": { name: "SEDAN", type: "Etios, Dzire - 4 Seater" },
      "Innova (7+1)": { name: "INNOVA", type: "7 Seater" },
      "Crysta (7+1)": { name: "INNOVA CRYSTA", type: "7 Seater" },
      "Tempo Traveller 14-Seater": { name: "TEMPOTRAVELLER 14", type: "12 - 14 Seater" },
      "Tempo Traveller 18-Seater": { name: "TEMPOTRAVELLER 18", type: "16 - 18 Seater" },
      "Urbania 12-Seater/16-Seater": { name: "URBANIA", type: "12 - 17 Seater" }
    };
    return map[vehicle] || { name: vehicle.toUpperCase(), type: "Private vehicle" };
  }

  function renderPackage() {
    const pkg = getPackage();
    if (!pkg) return;

    heading.textContent = `${dayText(days)} Tour Package`;
    sub.textContent = "Choose a vehicle and review the complete itinerary.";
    routeLine.textContent = routeKey;

    if (activeAnchor) activeAnchor.id = pkg.id;
    document.getElementById("tariffSection")?.setAttribute("data-package-id", pkg.id);

    const extra = hotelExtra(pkg);
    tbody.innerHTML = Object.entries(pkg.prices).map(([vehicle, price]) => {
      const display = vehicleDisplay(vehicle);
      const isRequest = price === null || price === undefined;
      const total = isRequest ? null : Number(price) + extra;
      return `<tr id="${pkg.id}-${slug(vehicle)}">
        <td><div class="vehicle-name">${display.name}</div><div class="vehicle-type">${display.type}</div></td>
        <td><div class="price-main">${isRequest ? "On Request" : `₹${total.toLocaleString("en-IN")}`}</div></td>
        <td><button type="button" class="btn-book-table ${isRequest ? "is-request" : ""}" data-vehicle="${vehicle}" data-price="${isRequest ? "" : total}">${isRequest ? "CALL US" : "BOOK NOW"}</button></td>
      </tr>`;
    }).join("");

    itinerary.innerHTML = pkg.itinerary.map((line, index) => `<tr id="${pkg.id}-day-${index + 1}"><th>Day ${index + 1}</th><td>${line.replace(/^Day\s*\d+:\s*/i, "")}</td></tr>`).join("");

    tbody.querySelectorAll(".btn-book-table").forEach(button => {
      button.addEventListener("click", () => {
        if (!button.dataset.price) {
          window.location.href = "tel:+919944165207";
          return;
        }
        openModal(button.dataset.vehicle, Number(button.dataset.price));
      });
    });

    hotelFields.classList.toggle("show", withHotel && pkg.nights > 0);
    document.getElementById("tourFilterCard").style.display = pkg.nights > 0 ? "block" : "none";
    hotelSwitch.closest(".col-md-3").style.display = pkg.nights > 0 ? "" : "none";
  }

  function renderAll() {
    renderTabs();
    renderSide();
    renderPackage();
  }

  function openModal(vehicle, price) {
    const pkg = getPackage();
    document.getElementById("sumPackage").textContent = routeKey;
    document.getElementById("sumVehicle").textContent = vehicle;
    document.getElementById("sumPrice").textContent = `₹${price.toLocaleString("en-IN")}`;
    document.getElementById("bookVehicle").value = vehicle;
    document.getElementById("bookPrice").value = price;
    document.getElementById("pickupDateTime").min = new Date(Date.now() - new Date().getTimezoneOffset() * 60000).toISOString().slice(0, 16);
    bootstrap.Modal.getOrCreateInstance(document.getElementById("bookingModal")).show();
  }

  hotelSwitch.addEventListener("click", () => {
    withHotel = !withHotel;
    hotelSwitch.classList.toggle("active", withHotel);
    hotelSwitch.setAttribute("aria-pressed", String(withHotel));
    renderPackage();
  });

  ["hotelType", "occupancy", "rooms"].forEach(id => document.getElementById(id).addEventListener("input", renderPackage));
  document.getElementById("scrollLeftBtn").addEventListener("click", () => tabs.scrollBy({ left: -320, behavior: "smooth" }));
  document.getElementById("scrollRightBtn").addEventListener("click", () => tabs.scrollBy({ left: 320, behavior: "smooth" }));

  document.getElementById("bookingFormTour").addEventListener("submit", event => {
    event.preventDefault();
    const value = id => document.getElementById(id).value.trim();
    const phone = value("bookPhone").replace(/\D/g, "");
    if (phone.length !== 10) {
      alert("Please enter a valid 10-digit mobile number.");
      return;
    }
    const pkg = getPackage();
    const message = `*Tour Package Enquiry — Ravi G Tours & Travels*\n\n📦 Package: ${routeKey}\n🔗 Package ID: ${pkg.id}\n🚘 Vehicle: ${value("bookVehicle")}\n💰 Tariff: ₹${Number(value("bookPrice")).toLocaleString("en-IN")}\n🏨 Accommodation: ${withHotel ? "Yes" : "No"}\n\n👤 Name: ${value("bookName")}\n📞 Phone: ${phone}\n📍 Pickup: ${value("pickupLocation")}\n📅 Pickup: ${value("pickupDateTime")}\n🏁 Drop: ${value("dropLocation")}\n\n🧭 Itinerary:\n${pkg.itinerary.join("\n")}\n\nPlease confirm availability and final fare.`;
    window.open(`https://wa.me/919944165207?text=${encodeURIComponent(message)}`, "_blank");
  });

  function selectFromHash() {
    const hash = location.hash.slice(1);
    if (!hash) return false;

    const tabDay = Object.keys(packagesByDays).find(day => packageTabId(Number(day)) === hash);
    if (tabDay) {
      days = Number(tabDay);
      routeKey = routeEntries(days)[0]?.[0] || "";
      return true;
    }

    for (const day of Object.keys(packagesByDays)) {
      const match = Object.entries(packagesByDays[day]).find(([route, pkg]) => pkg.id === hash || slug(route) === hash);
      if (match) {
        days = Number(day);
        routeKey = match[0];
        return true;
      }
    }
    return false;
  }

  const hadHash = selectFromHash();
  renderAll();
  if (hadHash) requestAnimationFrame(() => tourSection?.scrollIntoView({ block: "start" }));

  window.addEventListener("hashchange", () => {
    if (selectFromHash()) renderAll();
  });
});
